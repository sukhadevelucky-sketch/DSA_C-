#include <iostream>
using namespace std;
int main()
{
    int a, b;
    cout << "Enter the any two number :" << endl;
    cin >> a >> b;
    cout << "Addition is = " << a + b << endl;
    cout << "Subtraction is = " << a - b << endl;
    cout << "Division = " << a / b << endl;
    cout << "Multiplication = " << a * b << endl;
    cout << "Module = " << a % b << endl;
}
